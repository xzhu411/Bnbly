const Categories = () => {
    const router = useRouter();
    const searchParams = useSearchParams();
    const activeCategory = searchParams.get('category');

    const handleClick = (label: string) => {
        const params = new URLSearchParams(searchParams.toString());
        if (activeCategory === label) {
            params.delete('category');
        } else {
            params.set('category', label);
        }
        router.push(`/?${params.toString()}`);
    };

    return (
        <div className="pt-3 cursor-pointer pb-6 flex items-center justify-center gap-10 overflow-x-auto">
            {categories.map((cat) => {
                const isActive = activeCategory === cat.label;
                return (
                    <div
                        key={cat.label}
                        onClick={() => handleClick(cat.label)}
                        className={`pb-3 flex flex-col items-center space-y-2 border-b-2 transition shrink-0 ${
                            isActive
                                ? 'border-gray-800 opacity-100'
                                : 'border-transparent opacity-60 hover:opacity-100 hover:border-gray-200'
                        }`}
                    >
                        {cat.icon}
                        <span className="text-xs font-medium">{cat.label}</span>
                    </div>
                );
            })}
        </div>
    );
};

export default Categories;
